/**
 * Get the quote for today based on the day of the year (1-365/366)
 */
export function getTodayQuote(): string {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  // Handle day 366 in leap years
  const quoteIndex = Math.min(dayOfYear - 1, DAILY_QUOTES.length - 1);
  
  return DAILY_QUOTES[quoteIndex];
}

/**
 * Get a quote for a specific date
 */
export function getQuoteForDate(date: Date): string {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  
  // Handle day 366 in leap years
  const quoteIndex = Math.min(dayOfYear - 1, DAILY_QUOTES.length - 1);
  
  return DAILY_QUOTES[quoteIndex];
}
